# python supports several built-in data types that can be used to store different types of values. Some of the most commonly used data types in Python are:
# 1. Integer (int): Represents whole numbers.
# 2. Float (float): Represents decimal numbers.
# 3. String (str): Represents a sequence of characters.
# 4. Boolean (bool): Represents True or False values.
# 5. List (list): Represents an ordered collection of items.
# 6. Tuple (tuple): Represents an ordered, immutable collection of items.
# 7. Dictionary (dict): Represents a collection of key-value pairs.
# 8. Set (set): Represents an unordered collection of unique items.
# with examples of each data type:

# Integer
age = 34
print(age)
print(type(age))

# Float
cgpa = 3.5
print(cgpa)

# String
name = "John"
print(name)

# Boolean
is_student = True
print(is_student)

# List
fruits = ["apple", "banana", "orange","grape"]
print(fruits)
print(fruits[1])  # Accessing the second element of the list

# Tuple
coordinates = (340, 10, 20,30)
print(coordinates)

# Dictionary
person = {"name": "John", "age": 34}
print(person)

# Set
unique_numbers = {1, 2, 3, 4, 6, 5}
print(unique_numbers)
print(type(unique_numbers))
